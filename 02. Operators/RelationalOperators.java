import java.util.*;
public class RelationalOperators {
    public static void main(String[] args){
        int a = 10;
        int b = 5;
        // Equals to [==]
        System.out.println((a==b));
        // Not equals to [!=]
        System.out.println((a!=b));
        // Greater than [>]
        System.out.println((a>b));
        // Less than [<]
        System.out.println((a<b));
        // Greter than or equal to [>=]
        System.out.println((a>=b));
        // Less than or equal to [<=]
        System.out.println((a<=b));
    }
}
