import java.util.*;
public class AssignmentOperators {
    public static void main(String[] args){
        int a = 10;
        // a=a+10
        System.out.println(a+=10);
        // a=a-10
        System.out.println(a-=10);
        // a=a*10
        System.out.println(a*=10);
        // a=a/10
        System.out.println(a/=10);
    }
}
